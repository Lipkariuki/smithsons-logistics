"""Real HTTP checks against a disposable local auth fixture server.

Set LEGACY_AUTH_HTTP_BASE and LEGACY_AUTH_FIXTURE_JSON (mode-0600 synthetic
credentials generated by the local audit harness). Never point at production.
No mocked API responses. Unauthorized write tests must never reach handlers.
"""
import json
import os
from pathlib import Path
import unittest
from urllib.parse import urlsplit

import requests

BASE = os.environ.get('LEGACY_AUTH_HTTP_BASE')
FIXTURE = os.environ.get('LEGACY_AUTH_FIXTURE_JSON')


@unittest.skipUnless(BASE and FIXTURE, 'Requires an explicit disposable local HTTP fixture')
class LegacyAuthorizationHTTPTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if urlsplit(BASE).hostname not in {'localhost', '127.0.0.1', '::1'}:
            raise RuntimeError('Authorization verification refuses remote backends')
        cls.fixture = json.loads(Path(FIXTURE).read_text())
        cls.tokens = cls.fixture['tokens']

    def request(self, method, path, role=None, **kwargs):
        headers = {'Authorization': 'Bearer ' + self.tokens[role]} if role else {}
        return requests.request(method, BASE + path, headers=headers, timeout=10, **kwargs)

    def test_logins_and_current_user_preserved(self):
        for role, uid in [('admin', 1), ('owner', 2), ('driver', 3)]:
            with self.subTest(role=role):
                login = requests.post(BASE+'/login', data={'username': f'070000000{uid}',
                    'password': self.fixture['password']}, timeout=10)
                self.assertEqual(login.status_code, 200)
                response = self.request('GET', '/users/me', role)
                self.assertEqual(response.status_code, 200)
                self.assertEqual(response.json()['role'], role)

    def test_legacy_admin_reads_and_null_order_references(self):
        for path in ['/admin/orders', '/orders/', '/trips/', '/vehicles/', '/vehicles/1',
                     '/users/', '/reports/summary', '/expenses/', '/commissions/']:
            with self.subTest(path=path):
                self.assertEqual(self.request('GET', path, 'admin').status_code, 200)
                self.assertEqual(self.request('GET', path).status_code, 401)
                for role in ['owner', 'driver']:
                    self.assertEqual(self.request('GET', path, role).status_code, 403)
        orders = self.request('GET', '/orders/', 'admin').json()
        self.assertEqual(orders[0]['purchase_order_number'], '')
        self.assertEqual(orders[0]['dispatch_note_number'], '')

    def test_all_administrative_router_operations_deny_before_handler(self):
        schema = requests.get(BASE+'/openapi.json', timeout=10).json()
        checked = 0
        for path, operations in schema['paths'].items():
            if not any(path.startswith(prefix) for prefix in ['/admin/', '/orders/', '/trips/', '/reports/', '/expenses/', '/commissions/']):
                continue
            path = path.replace('{order_id}', '1').replace('{trip_id}', '1').replace('{vehicle_id}', '1').replace('{expense_id}', '1').replace('{commission_id}', '1')
            for method in operations:
                if method not in {'get', 'post', 'put', 'patch', 'delete'}:
                    continue
                for role, expected in [(None, 401), ('owner', 403), ('driver', 403)]:
                    with self.subTest(path=path, method=method, role=role):
                        response = self.request(method, path, role, json={})
                        self.assertEqual(response.status_code, expected)
                checked += 1
        self.assertGreaterEqual(checked, 15)

    def test_owner_and_driver_records_stay_scoped(self):
        for path, role in [('/partner/orders', 'owner'), ('/driver/trips', 'driver'),
                           ('/driver/expenses', 'driver')]:
            response = self.request('GET', path, role)
            self.assertEqual(response.status_code, 200)
            self.assertEqual([row['id'] for row in response.json()], [1])
        self.assertEqual(self.request('GET', '/partner-dashboard/', 'owner').status_code, 200)
        self.assertEqual(self.request('GET', '/driver/trips', 'owner').status_code, 403)
        self.assertEqual(self.request('GET', '/partner/orders', 'driver').status_code, 403)

    def test_dhl_and_monthly_financial_permissions_preserved(self):
        for path in ['/dhl-reports/summary', '/dhl-reports/reconciliation',
                     '/dhl-reports/monthly-net-summary?month=2026-10-01&version=1']:
            self.assertEqual(self.request('GET', path, 'admin').status_code, 200)
            self.assertEqual(self.request('GET', path).status_code, 401)
            for role in ['owner', 'driver']:
                self.assertEqual(self.request('GET', path, role).status_code, 403)
        summary = self.request('GET', '/dhl-reports/summary', 'admin').json()
        self.assertEqual(sum(row['total_revenue'] for row in summary), 3200)

    def test_expired_token_and_cors_preserved(self):
        response = requests.get(BASE+'/users/me', headers={'Authorization':'Bearer '+self.fixture['expired']}, timeout=10)
        self.assertEqual(response.status_code, 401)
        for origin, expected in [('http://localhost:8054', 200),
                                 ('https://smithsons-logistics-frontend.onrender.com', 200),
                                 ('https://evil.example', 400)]:
            response = requests.options(BASE+'/orders/', headers={'Origin':origin,
                'Access-Control-Request-Method':'GET', 'Access-Control-Request-Headers':'authorization'}, timeout=10)
            self.assertEqual(response.status_code, expected)

    def test_driver_submission_requires_own_trip_on_both_paths(self):
        for path in ['/driver/expenses', '/driver/expenses/']:
            body = {'trip_id': 2, 'amount': 3.25, 'description': 'Synthetic denied cross-driver write'}
            self.assertEqual(self.request('POST', path, 'driver', json=body).status_code, 400)
            self.assertEqual(self.request('POST', path, 'owner', json=body).status_code, 403)
            self.assertEqual(self.request('POST', path, json=body).status_code, 401)
            body['trip_id'] = 1
            body['description'] = 'Synthetic authorized driver write'
            response = self.request('POST', path, 'driver', json=body)
            self.assertEqual(response.status_code, 200)
            self.assertEqual(response.json()['trip_id'], 1)
            # Keep own-record fixture stable for subsequent tests.
            self.assertEqual(self.request('DELETE', '/expenses/'+str(response.json()['id']), 'admin').status_code, 200)

    def test_admin_expense_and_commission_workflows(self):
        response = self.request('POST', '/expenses/', 'admin', json={'trip_id':1, 'amount':12.34, 'description':'Synthetic admin expense'})
        self.assertEqual(response.status_code, 200)
        identifier = response.json()['id']
        self.assertEqual(self.request('PATCH', f'/expenses/{identifier}', 'admin', json={'amount':15.25}).status_code, 200)
        self.assertEqual(self.request('DELETE', f'/expenses/{identifier}', 'admin').status_code, 200)
        response = self.request('PUT', '/commissions/1?rate_percent=7', 'admin')
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.json()['amount_paid'], 70)
