-- Additive, explicit and transactional. No existing rows are altered/backfilled.
-- Apply only after separate production approval. Do not run on application startup.
CREATE TABLE dhl_monthly_workbooks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporting_month DATE NOT NULL CHECK (EXTRACT(DAY FROM reporting_month)=1),
 version INTEGER NOT NULL CHECK (version>0),
 original_filename TEXT NOT NULL CHECK (btrim(original_filename)<>''),
 content_sha256 TEXT NOT NULL CHECK (content_sha256 ~ '^[a-f0-9]{64}$'),
 content BYTEA NOT NULL CHECK (octet_length(content)>0 AND octet_length(content)<=20000000),
 uploaded_by BIGINT NOT NULL CHECK (uploaded_by>0),
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 previous_id BIGINT REFERENCES dhl_monthly_workbooks(id) ON DELETE RESTRICT,
 reason TEXT NOT NULL,
 date_review JSONB NOT NULL CHECK (jsonb_typeof(date_review)='object'),
 UNIQUE(reporting_month,version), UNIQUE(reporting_month,content_sha256),
 CHECK (content_sha256=encode(sha256(content),'hex'))
);
CREATE INDEX dhl_workbook_previous ON dhl_monthly_workbooks(previous_id);
CREATE FUNCTION dhl_workbook_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE latest dhl_monthly_workbooks;
BEGIN
 IF TG_OP<>'INSERT' THEN RAISE EXCEPTION 'Saved workbooks are immutable; upload a successor'; END IF;
 PERFORM pg_advisory_xact_lock(736281,extract(year FROM NEW.reporting_month)::int*12+extract(month FROM NEW.reporting_month)::int);
 SELECT * INTO latest FROM dhl_monthly_workbooks WHERE reporting_month=NEW.reporting_month ORDER BY version DESC LIMIT 1;
 IF FOUND THEN
  IF NEW.previous_id IS DISTINCT FROM latest.id OR NEW.version<>latest.version+1 OR btrim(NEW.reason)='' THEN
   RAISE EXCEPTION 'Replacement requires latest source version and audit reason';
  END IF;
 ELSIF NEW.previous_id IS NOT NULL OR NEW.version<>1 THEN RAISE EXCEPTION 'First source version must be version one';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER dhl_workbook_immutable BEFORE INSERT OR UPDATE OR DELETE ON dhl_monthly_workbooks FOR EACH ROW EXECUTE FUNCTION dhl_workbook_guard();
CREATE TRIGGER dhl_workbook_no_truncate BEFORE TRUNCATE ON dhl_monthly_workbooks FOR EACH STATEMENT EXECUTE FUNCTION dhl_workbook_guard();
