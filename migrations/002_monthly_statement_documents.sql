-- Separate release: apply explicitly in ONE transaction after backup/approval.
-- No legacy tables or monthly snapshots are altered. Never run at startup.
CREATE TABLE monthly_statement_documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_row_id BIGINT NOT NULL UNIQUE REFERENCES dhl_monthly_expense_rows(id) ON DELETE RESTRICT,
 previous_document_id BIGINT REFERENCES monthly_statement_documents(id) ON DELETE RESTRICT,
 pdf_content BYTEA NOT NULL CHECK (octet_length(pdf_content) > 0),
 pdf_sha256 VARCHAR(64) NOT NULL CHECK (pdf_sha256 ~ '^[a-f0-9]{64}$'),
 renderer_version TEXT NOT NULL CHECK (btrim(renderer_version) <> ''),
 generated_by BIGINT NOT NULL CHECK (generated_by > 0),
 generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX monthly_statement_previous ON monthly_statement_documents(previous_document_id);
CREATE FUNCTION monthly_statement_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE source_record RECORD; predecessor RECORD;
BEGIN
 IF TG_OP <> 'INSERT' THEN
  RAISE EXCEPTION 'Stored monthly statements are append-only';
 END IF;
 SELECT r.normalized_plate, i.reporting_month, i.version, i.status INTO source_record
 FROM dhl_monthly_expense_rows r JOIN dhl_monthly_expense_imports i ON i.id=r.import_id
 WHERE r.id=NEW.expense_row_id FOR UPDATE OF i;
 IF NOT FOUND OR source_record.status NOT IN ('confirmed', 'superseded') THEN
  RAISE EXCEPTION 'A new statement requires a confirmed monthly snapshot';
 END IF;
 IF NEW.previous_document_id IS NOT NULL THEN
  SELECT r.normalized_plate, i.reporting_month, i.version INTO predecessor
  FROM monthly_statement_documents d JOIN dhl_monthly_expense_rows r ON r.id=d.expense_row_id
  JOIN dhl_monthly_expense_imports i ON i.id=r.import_id WHERE d.id=NEW.previous_document_id;
  IF NOT FOUND OR predecessor.normalized_plate <> source_record.normalized_plate
    OR predecessor.reporting_month <> source_record.reporting_month
    OR predecessor.version >= source_record.version THEN
   RAISE EXCEPTION 'Predecessor must be an earlier statement for the same truck and month';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER monthly_statement_immutable BEFORE INSERT OR UPDATE OR DELETE ON monthly_statement_documents
 FOR EACH ROW EXECUTE FUNCTION monthly_statement_guard();
CREATE TRIGGER monthly_statement_no_truncate BEFORE TRUNCATE ON monthly_statement_documents
 FOR EACH STATEMENT EXECUTE FUNCTION monthly_statement_guard();
