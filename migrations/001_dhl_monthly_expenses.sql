-- Additive, explicit migration. Run in one transaction on a reviewed target only.
-- Not imported by main.py or any startup hook. Intentionally fails on rerun.
CREATE TABLE dhl_monthly_expense_imports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporting_month DATE NOT NULL CHECK (EXTRACT(DAY FROM reporting_month) = 1),
 version INTEGER NOT NULL CHECK (version > 0),
 status TEXT NOT NULL CHECK (status IN ('draft','confirmed','superseded')),
 original_filename TEXT NOT NULL,
 file_sha256 VARCHAR(64) NOT NULL CHECK (file_sha256 ~ '^[a-f0-9]{64}$'),
 source_content BYTEA NOT NULL,
 decisions JSONB NOT NULL CHECK (jsonb_typeof(decisions) = 'object'),
 decisions_sha256 VARCHAR(64) NOT NULL CHECK (decisions_sha256 ~ '^[a-f0-9]{64}$'),
 header_mappings JSONB NOT NULL CHECK (jsonb_typeof(header_mappings) = 'array'),
 assumptions JSONB NOT NULL CHECK (jsonb_typeof(assumptions) = 'array'),
 issues JSONB NOT NULL CHECK (jsonb_typeof(issues) = 'array'),
 dhl_source_fingerprint VARCHAR(64) NOT NULL CHECK (dhl_source_fingerprint ~ '^[a-f0-9]{64}$'),
 source_verification TEXT NOT NULL,
 calculation_policy JSONB NOT NULL CHECK (jsonb_typeof(calculation_policy) = 'object'),
 uploader_id BIGINT NOT NULL CHECK (uploader_id > 0),
 confirmer_id BIGINT CHECK (confirmer_id > 0),
 created_at TIMESTAMPTZ NOT NULL,
 confirmed_at TIMESTAMPTZ,
 previous_version_id BIGINT REFERENCES dhl_monthly_expense_imports(id) ON DELETE RESTRICT,
 UNIQUE (reporting_month, version),
 UNIQUE (reporting_month, file_sha256, decisions_sha256, dhl_source_fingerprint),
 CHECK ((status = 'draft' AND confirmed_at IS NULL AND confirmer_id IS NULL)
     OR (status IN ('confirmed','superseded') AND confirmed_at IS NOT NULL AND confirmer_id IS NOT NULL)),
 CHECK (previous_version_id IS NULL OR previous_version_id <> id)
);
CREATE UNIQUE INDEX dhl_monthly_one_confirmed ON dhl_monthly_expense_imports(reporting_month) WHERE status = 'confirmed';
CREATE INDEX dhl_monthly_file_lookup ON dhl_monthly_expense_imports(reporting_month, file_sha256);
CREATE INDEX dhl_monthly_previous_lookup ON dhl_monthly_expense_imports(previous_version_id);
CREATE TABLE dhl_monthly_expense_rows (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 import_id BIGINT NOT NULL REFERENCES dhl_monthly_expense_imports(id) ON DELETE RESTRICT,
 source_worksheet TEXT NOT NULL,
 source_row INTEGER NOT NULL CHECK (source_row > 0),
 original_plate TEXT NOT NULL,
 normalized_plate TEXT NOT NULL,
 vehicle_id BIGINT,
 vehicle_owner_snapshot JSONB NOT NULL CHECK (jsonb_typeof(vehicle_owner_snapshot) = 'object'),
 deductions JSONB NOT NULL CHECK (jsonb_typeof(deductions) = 'object'),
 cell_audit JSONB NOT NULL CHECK (jsonb_typeof(cell_audit) = 'object'),
 dhl_source_snapshot JSONB NOT NULL CHECK (jsonb_typeof(dhl_source_snapshot) = 'array'),
 revenue_status TEXT NOT NULL CHECK (revenue_status IN ('dhl_records','verified_no_activity','missing','incomplete','unimported')),
 revenue_evidence TEXT NOT NULL,
 gross NUMERIC(18,2), operating_expenses NUMERIC(18,2), commission_base NUMERIC(18,2),
 commission NUMERIC(18,2), net_payable NUMERIC(18,2),
 issues JSONB NOT NULL CHECK (jsonb_typeof(issues) = 'array'),
 CHECK (gross IS NULL OR gross::text NOT IN ('NaN','Infinity','-Infinity')),
 CHECK (operating_expenses IS NULL OR operating_expenses::text NOT IN ('NaN','Infinity','-Infinity')),
 CHECK (commission_base IS NULL OR commission_base::text NOT IN ('NaN','Infinity','-Infinity')),
 CHECK (commission IS NULL OR commission::text NOT IN ('NaN','Infinity','-Infinity')),
 CHECK (net_payable IS NULL OR net_payable::text NOT IN ('NaN','Infinity','-Infinity')),
 UNIQUE (import_id, source_worksheet, source_row)
 -- Duplicate truck rows may be retained in invalid drafts for review; confirmation blocks them.
);
CREATE INDEX dhl_monthly_truck_lookup ON dhl_monthly_expense_rows(import_id, normalized_plate);

CREATE FUNCTION dhl_monthly_guard_row() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE parent_status TEXT;
BEGIN
 IF TG_OP = 'UPDATE' AND NEW.import_id <> OLD.import_id THEN
  RAISE EXCEPTION 'Cannot move an expense row between imports';
 END IF;
 SELECT status INTO parent_status FROM dhl_monthly_expense_imports
 WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.import_id ELSE NEW.import_id END FOR UPDATE;
 IF parent_status IS DISTINCT FROM 'draft' THEN
  RAISE EXCEPTION 'Confirmed/superseded expense rows are immutable';
 END IF;
 IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER dhl_monthly_row_guard BEFORE INSERT OR UPDATE OR DELETE ON dhl_monthly_expense_rows
 FOR EACH ROW EXECUTE FUNCTION dhl_monthly_guard_row();

CREATE FUNCTION dhl_monthly_guard_import() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE r RECORD; entry RECORD; deduction_total NUMERIC; categories JSONB;
BEGIN
 IF TG_OP = 'DELETE' THEN
  IF OLD.status <> 'draft' THEN RAISE EXCEPTION 'Confirmed history is immutable'; END IF;
  RETURN OLD;
 END IF;
 IF TG_OP = 'INSERT' AND NEW.status <> 'draft' THEN
  RAISE EXCEPTION 'Imports must start as drafts';
 END IF;
 IF TG_OP = 'UPDATE' AND OLD.status <> 'draft' THEN
  IF NOT (OLD.status = 'confirmed' AND NEW.status = 'superseded'
     AND (to_jsonb(NEW) - 'status') = (to_jsonb(OLD) - 'status')) THEN
   RAISE EXCEPTION 'Confirmed history is immutable except supersession';
  END IF;
 END IF;
 IF TG_OP = 'UPDATE' AND OLD.status = 'draft' AND NEW.status = 'superseded' THEN
  RAISE EXCEPTION 'Only confirmed reports can be superseded';
 END IF;
 IF NEW.previous_version_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM dhl_monthly_expense_imports p WHERE p.id = NEW.previous_version_id
    AND p.reporting_month = NEW.reporting_month AND p.version < NEW.version) THEN
  RAISE EXCEPTION 'Previous version must be an earlier version of the same month';
 END IF;
 IF TG_OP = 'UPDATE' AND OLD.status = 'draft' AND NEW.status = 'confirmed' THEN
  IF btrim(NEW.source_verification) = '' OR EXISTS (
    SELECT 1 FROM jsonb_array_elements(NEW.issues) x WHERE (x->>'blocking')::boolean IS DISTINCT FROM false) THEN
   RAISE EXCEPTION 'Unresolved import validation/source verification';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM dhl_monthly_expense_rows WHERE import_id = NEW.id) THEN
   RAISE EXCEPTION 'Cannot confirm an empty import';
  END IF;
  IF EXISTS (SELECT 1 FROM dhl_monthly_expense_rows WHERE import_id = NEW.id GROUP BY normalized_plate HAVING count(*) > 1) THEN
   RAISE EXCEPTION 'Duplicate truck registration';
  END IF;
  SELECT jsonb_agg(h->>'category') INTO categories FROM jsonb_array_elements(NEW.header_mappings) h
    WHERE h->>'classification' = 'expense';
  IF categories IS NULL OR EXISTS (
    SELECT 1 FROM jsonb_array_elements(NEW.header_mappings) h WHERE h->>'classification' = 'unknown') OR EXISTS (
    SELECT 1 FROM jsonb_array_elements_text(categories) c GROUP BY c HAVING count(*) > 1) THEN
   RAISE EXCEPTION 'Unapproved or duplicate expense category mappings';
  END IF;
  FOR r IN SELECT * FROM dhl_monthly_expense_rows WHERE import_id = NEW.id LOOP
   IF r.vehicle_id IS NULL OR r.normalized_plate !~ '^[A-Z0-9]+$'
     OR r.revenue_status NOT IN ('dhl_records','verified_no_activity')
     OR btrim(r.revenue_evidence) = '' OR r.gross IS NULL OR r.operating_expenses IS NULL
     OR r.commission_base IS NULL OR r.commission IS NULL OR r.net_payable IS NULL
     OR (r.revenue_status = 'verified_no_activity' AND r.gross <> 0)
     OR EXISTS (SELECT 1 FROM jsonb_array_elements(r.issues) x WHERE (x->>'blocking')::boolean IS DISTINCT FROM false) THEN
    RAISE EXCEPTION 'Unresolved expense row validation';
   END IF;
   deduction_total := 0;
   FOR entry IN SELECT key, value FROM jsonb_each(r.deductions) LOOP
    IF jsonb_typeof(entry.value->'amount') IS DISTINCT FROM 'string'
      OR (entry.value->>'amount') !~ '^-?[0-9]+\.[0-9]{2}$'
      OR NOT (categories ? entry.key OR (entry.key = 'kasarani_ksm_fuel'
        AND entry.value->>'amount' = '0.00' AND entry.value->>'resolution' = 'absent_optional_category')) THEN
     RAISE EXCEPTION 'Invalid or unapproved deduction JSON';
    END IF;
    deduction_total := deduction_total + (entry.value->>'amount')::numeric;
   END LOOP;
   IF EXISTS (SELECT 1 FROM jsonb_array_elements_text(categories) c WHERE NOT (r.deductions ? c))
     OR r.operating_expenses <> deduction_total OR r.commission_base <> r.gross - deduction_total
     OR r.commission <> round(greatest(r.commission_base, 0) * 0.07, 2)
     OR r.net_payable <> r.commission_base - r.commission THEN
    RAISE EXCEPTION 'Financial totals do not match approved deductions';
   END IF;
  END LOOP;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER dhl_monthly_import_guard BEFORE INSERT OR UPDATE OR DELETE ON dhl_monthly_expense_imports
 FOR EACH ROW EXECUTE FUNCTION dhl_monthly_guard_import();
