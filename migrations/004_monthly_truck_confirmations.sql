-- Explicit, transactional release migration AFTER 001, 002 and 003.
-- No legacy orders/trips/payslip records are changed. Never run at startup.
LOCK TABLE dhl_monthly_expense_imports,dhl_monthly_expense_rows IN ACCESS EXCLUSIVE MODE;
CREATE TABLE dhl_monthly_truck_confirmations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_row_id BIGINT NOT NULL UNIQUE REFERENCES dhl_monthly_expense_rows(id) ON DELETE RESTRICT,
 reporting_month DATE NOT NULL,
 normalized_plate TEXT NOT NULL CHECK (normalized_plate ~ '^[A-Z0-9]+$'),
 report_version INTEGER NOT NULL CHECK (report_version>0),
 status TEXT NOT NULL CHECK (status IN ('current','superseded')),
 method TEXT NOT NULL CHECK (method IN ('truck','month')),
 previous_confirmation_id BIGINT REFERENCES dhl_monthly_truck_confirmations(id) ON DELETE RESTRICT,
 confirmer_id BIGINT NOT NULL CHECK (confirmer_id>0),
 confirmed_at TIMESTAMPTZ NOT NULL,
 reason TEXT NOT NULL CHECK (btrim(reason)<>''),
 row_sha256 TEXT NOT NULL CHECK (row_sha256 ~ '^[a-f0-9]{64}$'),
 parent_sha256 TEXT NOT NULL CHECK (parent_sha256 ~ '^[a-f0-9]{64}$'),
 source_sha256 TEXT NOT NULL CHECK (source_sha256 ~ '^[a-f0-9]{64}$'),
 validation JSONB NOT NULL CHECK (jsonb_typeof(validation)='object')
);
CREATE UNIQUE INDEX dhl_truck_one_current ON dhl_monthly_truck_confirmations(reporting_month,normalized_plate) WHERE status='current';
CREATE INDEX dhl_truck_previous ON dhl_monthly_truck_confirmations(previous_confirmation_id);

CREATE FUNCTION dhl_truck_row_hash(row_id BIGINT) RETURNS TEXT LANGUAGE SQL STABLE AS $$
 SELECT encode(sha256(convert_to(to_jsonb(r)::text,'UTF8')),'hex') FROM dhl_monthly_expense_rows r WHERE r.id=row_id
$$;
CREATE FUNCTION dhl_truck_parent_hash(import_id BIGINT) RETURNS TEXT LANGUAGE SQL STABLE AS $$
 SELECT encode(sha256(convert_to(((to_jsonb(i)-'status'-'confirmer_id'-'confirmed_at'-'created_at')
  || jsonb_build_object('created_at_epoch',extract(epoch FROM i.created_at)))::text,'UTF8')),'hex')
 FROM dhl_monthly_expense_imports i WHERE i.id=import_id
$$;
CREATE FUNCTION dhl_truck_source_hash(row_id BIGINT) RETURNS TEXT LANGUAGE SQL STABLE AS $$
 SELECT encode(sha256(convert_to(r.dhl_source_snapshot::text,'UTF8')),'hex') FROM dhl_monthly_expense_rows r WHERE r.id=row_id
$$;

CREATE FUNCTION dhl_truck_confirmation_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE r dhl_monthly_expense_rows; p dhl_monthly_expense_imports; prev dhl_monthly_truck_confirmations;
 categories JSONB; entry RECORD; total NUMERIC; prior_row dhl_monthly_expense_rows;
BEGIN
 IF TG_OP='UPDATE' THEN
  IF OLD.status='current' AND NEW.status='superseded' AND to_jsonb(OLD)-'status'=to_jsonb(NEW)-'status' THEN RETURN NEW; END IF;
  RAISE EXCEPTION 'Truck confirmations are immutable except explicit supersession';
 END IF;
 IF TG_OP<>'INSERT' THEN RAISE EXCEPTION 'Truck confirmation history cannot be deleted or truncated'; END IF;
 SELECT * INTO r FROM dhl_monthly_expense_rows WHERE id=NEW.expense_row_id;
 SELECT * INTO p FROM dhl_monthly_expense_imports WHERE id=r.import_id;
 PERFORM pg_advisory_xact_lock(736281, EXTRACT(YEAR FROM p.reporting_month)::int*12+EXTRACT(MONTH FROM p.reporting_month)::int);
 SELECT * INTO p FROM dhl_monthly_expense_imports WHERE id=r.import_id FOR UPDATE;
 SELECT * INTO r FROM dhl_monthly_expense_rows WHERE id=NEW.expense_row_id;
 IF NEW.status<>'current' OR NEW.reporting_month<>p.reporting_month OR NEW.normalized_plate<>r.normalized_plate
   OR NEW.report_version<>p.version OR NEW.row_sha256 IS DISTINCT FROM dhl_truck_row_hash(r.id)
   OR NEW.parent_sha256 IS DISTINCT FROM dhl_truck_parent_hash(p.id)
   OR NEW.source_sha256 IS DISTINCT FROM dhl_truck_source_hash(r.id)
   OR NEW.validation->>'verified' IS DISTINCT FROM 'true' OR NEW.validation->>'scope_plate' IS DISTINCT FROM r.normalized_plate
   OR (NEW.method='month' AND p.status<>'confirmed') OR (NEW.method='truck' AND p.status<>'draft') THEN
  RAISE EXCEPTION 'Truck confirmation must identify the verified exact financial source';
 END IF;
 SELECT * INTO prev FROM dhl_monthly_truck_confirmations WHERE reporting_month=p.reporting_month
  AND normalized_plate=r.normalized_plate ORDER BY report_version DESC LIMIT 1;
 IF FOUND AND (NEW.previous_confirmation_id IS DISTINCT FROM prev.id OR prev.report_version>=p.version OR prev.status<>'superseded') THEN
  RAISE EXCEPTION 'Correction must explicitly supersede the latest older truck confirmation';
 ELSIF NOT FOUND AND NEW.previous_confirmation_id IS NOT NULL THEN
  RAISE EXCEPTION 'Invalid predecessor confirmation';
 END IF;
 -- A correction records its own immutable difference; it never edits a payment
 -- or infers that the statement was paid. Amounts are decimal strings.
 IF NEW.previous_confirmation_id IS NOT NULL THEN
  SELECT * INTO prior_row FROM dhl_monthly_expense_rows WHERE id=prev.expense_row_id;
  NEW.validation := NEW.validation || jsonb_build_object('financial_adjustment',jsonb_build_object(
   'kind','statement_correction','previous_confirmation_id',prev.id,'previous_expense_row_id',prior_row.id,
   'previous_net_payable',prior_row.net_payable::text,'revised_net_payable',r.net_payable::text,
   'gross_difference',(r.gross-prior_row.gross)::numeric(18,2)::text,
   'expenses_difference',(r.operating_expenses-prior_row.operating_expenses)::numeric(18,2)::text,
   'commission_difference',(r.commission-prior_row.commission)::numeric(18,2)::text,
   'net_payable_difference',(r.net_payable-prior_row.net_payable)::numeric(18,2)::text,
   'payment_processing',false,'payment_status','not_assessed'));
 ELSIF NEW.validation ? 'financial_adjustment' THEN
  RAISE EXCEPTION 'An adjustment requires an earlier confirmed statement';
 END IF;
 IF r.vehicle_id IS NULL OR r.gross IS NULL OR r.operating_expenses IS NULL OR r.commission_base IS NULL
   OR r.commission IS NULL OR r.net_payable IS NULL OR r.revenue_status NOT IN ('dhl_records','verified_no_activity')
   OR btrim(r.revenue_evidence)='' OR btrim(p.source_verification)=''
   OR (r.revenue_status='verified_no_activity' AND r.gross<>0)
   OR EXISTS (SELECT 1 FROM jsonb_array_elements(r.issues) i WHERE (i->>'blocking')::boolean IS DISTINCT FROM false)
   OR (SELECT count(*) FROM dhl_monthly_expense_rows WHERE import_id=p.id AND normalized_plate=r.normalized_plate)<>1 THEN
  RAISE EXCEPTION 'Unresolved target-truck financial validation';
 END IF;
 SELECT coalesce(jsonb_agg(h->>'category'),'[]'::jsonb) INTO categories FROM jsonb_array_elements(p.header_mappings) h WHERE h->>'classification'='expense';
 IF EXISTS (SELECT 1 FROM jsonb_array_elements(p.header_mappings) h WHERE h->>'classification'='unknown')
  OR EXISTS (SELECT 1 FROM jsonb_array_elements_text(categories) c GROUP BY c HAVING count(*)>1) THEN
  RAISE EXCEPTION 'Unapproved or duplicate expense mappings';
 END IF;
 total:=0;
 FOR entry IN SELECT key,value FROM jsonb_each(r.deductions) LOOP
  IF jsonb_typeof(entry.value->'amount') IS DISTINCT FROM 'string' OR (entry.value->>'amount') !~ '^-?[0-9]+\.[0-9]{2}$'
   OR NOT (categories ? entry.key OR (entry.key='kasarani_ksm_fuel' AND entry.value->>'amount'='0.00' AND entry.value->>'resolution'='absent_optional_category')) THEN
   RAISE EXCEPTION 'Invalid deduction snapshot';
  END IF;
  total:=total+(entry.value->>'amount')::numeric;
 END LOOP;
 IF EXISTS (SELECT 1 FROM jsonb_array_elements_text(categories) c WHERE NOT (r.deductions ? c))
  OR total<>r.operating_expenses OR r.commission_base<>r.gross-total
  OR r.commission<>round(greatest(r.commission_base,0)*0.07,2) OR r.net_payable<>r.commission_base-r.commission THEN
  RAISE EXCEPTION 'Truck totals do not match approved deductions';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER dhl_truck_confirm_guard BEFORE INSERT OR UPDATE OR DELETE ON dhl_monthly_truck_confirmations FOR EACH ROW EXECUTE FUNCTION dhl_truck_confirmation_guard();
CREATE TRIGGER dhl_truck_no_truncate BEFORE TRUNCATE ON dhl_monthly_truck_confirmations FOR EACH STATEMENT EXECUTE FUNCTION dhl_truck_confirmation_guard();

CREATE FUNCTION dhl_truck_successor_required() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status='superseded' AND NOT EXISTS (SELECT 1 FROM dhl_monthly_truck_confirmations WHERE previous_confirmation_id=NEW.id) THEN
  RAISE EXCEPTION 'Supersession must create a successor confirmation in the same transaction';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER dhl_truck_successor AFTER UPDATE ON dhl_monthly_truck_confirmations
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION dhl_truck_successor_required();

CREATE FUNCTION dhl_truck_freeze_parent() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS (SELECT 1 FROM dhl_monthly_truck_confirmations c JOIN dhl_monthly_expense_rows r ON r.id=c.expense_row_id WHERE r.import_id=OLD.id) THEN
  IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Truck-confirmed source version cannot be deleted'; END IF;
  IF (to_jsonb(NEW)-'status'-'confirmer_id'-'confirmed_at')<>(to_jsonb(OLD)-'status'-'confirmer_id'-'confirmed_at')
   OR NOT ((OLD.status='draft' AND NEW.status='confirmed') OR (OLD.status='confirmed' AND NEW.status='superseded') OR to_jsonb(NEW)=to_jsonb(OLD)) THEN
   RAISE EXCEPTION 'Truck-confirmed workbook version is frozen; create a new version';
  END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
CREATE TRIGGER dhl_truck_parent_freeze BEFORE UPDATE OR DELETE ON dhl_monthly_expense_imports FOR EACH ROW EXECUTE FUNCTION dhl_truck_freeze_parent();
CREATE FUNCTION dhl_truck_freeze_rows() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE parent BIGINT;
BEGIN
 parent:=CASE WHEN TG_OP='DELETE' THEN OLD.import_id ELSE NEW.import_id END;
 IF EXISTS (SELECT 1 FROM dhl_monthly_truck_confirmations c JOIN dhl_monthly_expense_rows r ON r.id=c.expense_row_id WHERE r.import_id=parent) THEN
  RAISE EXCEPTION 'Rows of a truck-confirmed report are frozen; create a new version';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
CREATE TRIGGER dhl_truck_rows_freeze BEFORE INSERT OR UPDATE OR DELETE ON dhl_monthly_expense_rows FOR EACH ROW EXECUTE FUNCTION dhl_truck_freeze_rows();

-- Whole-month confirmation continues to use its existing complete validation.
-- Explicit truck corrections may not be overwritten by a whole-month action.
CREATE FUNCTION dhl_truck_sync_month() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE r RECORD; prev dhl_monthly_truck_confirmations;
BEGIN
 IF NEW.status='confirmed' AND OLD.status='draft' THEN
  FOR r IN SELECT * FROM dhl_monthly_expense_rows WHERE import_id=NEW.id ORDER BY normalized_plate LOOP
   SELECT * INTO prev FROM dhl_monthly_truck_confirmations WHERE reporting_month=NEW.reporting_month AND normalized_plate=r.normalized_plate AND status='current';
   IF FOUND AND prev.expense_row_id=r.id THEN CONTINUE; END IF;
   IF FOUND AND (prev.method='truck' OR prev.report_version>=NEW.version) THEN
    RAISE EXCEPTION 'Explicitly confirm this truck correction before confirming the month';
   END IF;
   IF FOUND THEN UPDATE dhl_monthly_truck_confirmations SET status='superseded' WHERE id=prev.id; END IF;
   INSERT INTO dhl_monthly_truck_confirmations(expense_row_id,reporting_month,normalized_plate,report_version,status,method,previous_confirmation_id,confirmer_id,confirmed_at,reason,row_sha256,parent_sha256,source_sha256,validation)
   VALUES(r.id,NEW.reporting_month,r.normalized_plate,NEW.version,'current','month',prev.id,NEW.confirmer_id,NEW.confirmed_at,
    'Whole-month confirmation',dhl_truck_row_hash(r.id),dhl_truck_parent_hash(NEW.id),
    encode(sha256(convert_to(r.dhl_source_snapshot::text,'UTF8')),'hex'),jsonb_build_object('verified',true,'scope_plate',r.normalized_plate,'policy','whole-month'));
  END LOOP;
 END IF; RETURN NULL;
END $$;
CREATE TRIGGER dhl_truck_month_sync AFTER UPDATE ON dhl_monthly_expense_imports FOR EACH ROW EXECUTE FUNCTION dhl_truck_sync_month();

-- Register existing CURRENT whole-month approvals; source rows/PDFs are untouched.
INSERT INTO dhl_monthly_truck_confirmations(expense_row_id,reporting_month,normalized_plate,report_version,status,method,confirmer_id,confirmed_at,reason,row_sha256,parent_sha256,source_sha256,validation)
 SELECT r.id,i.reporting_month,r.normalized_plate,i.version,'current','month',i.confirmer_id,i.confirmed_at,
 'Existing confirmed month registered during migration',dhl_truck_row_hash(r.id),dhl_truck_parent_hash(i.id),
 encode(sha256(convert_to(r.dhl_source_snapshot::text,'UTF8')),'hex'),jsonb_build_object('verified',true,'scope_plate',r.normalized_plate,'policy','existing-whole-month')
 FROM dhl_monthly_expense_imports i JOIN dhl_monthly_expense_rows r ON r.import_id=i.id WHERE i.status='confirmed';

-- The document source row remains the financial FK; no historical PDFs rewritten.
CREATE OR REPLACE FUNCTION monthly_statement_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE source_record RECORD; predecessor RECORD;
BEGIN
 IF TG_OP<>'INSERT' THEN RAISE EXCEPTION 'Stored monthly statements are append-only'; END IF;
 SELECT r.normalized_plate,i.reporting_month,i.version,i.status,r.id AS row_id INTO source_record
 FROM dhl_monthly_expense_rows r JOIN dhl_monthly_expense_imports i ON i.id=r.import_id WHERE r.id=NEW.expense_row_id FOR UPDATE OF i;
 IF NOT FOUND OR (source_record.status NOT IN ('confirmed','superseded') AND NOT EXISTS (
   SELECT 1 FROM dhl_monthly_truck_confirmations WHERE expense_row_id=source_record.row_id)) THEN
  RAISE EXCEPTION 'An immutable truck or monthly confirmation is required';
 END IF;
 IF NEW.previous_document_id IS NOT NULL THEN
  SELECT r.normalized_plate,i.reporting_month,i.version INTO predecessor FROM monthly_statement_documents d
   JOIN dhl_monthly_expense_rows r ON r.id=d.expense_row_id JOIN dhl_monthly_expense_imports i ON i.id=r.import_id WHERE d.id=NEW.previous_document_id;
  IF NOT FOUND OR predecessor.normalized_plate<>source_record.normalized_plate OR predecessor.reporting_month<>source_record.reporting_month OR predecessor.version>=source_record.version THEN
   RAISE EXCEPTION 'Invalid statement predecessor';
  END IF;
 END IF; RETURN NEW;
END $$;
